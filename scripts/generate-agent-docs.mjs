import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { buildCapabilities } from '../src/capabilities.js';
import { buildProgram } from '../src/cli.js';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8'));
const outputPath = join(root, 'docs', 'agent-protocol.md');
const capabilities = buildCapabilities({ cliVersion: pkg.version });

function commands(program, prefix = 'scope') {
  return program.commands.flatMap((command) => {
    const path = `${prefix} ${command.name()}`;
    const own = `- \`${path}${command.usage() ? ` ${command.usage()}` : ''}\` — ${command.description() || 'No description.'}`;
    return [own, ...commands(command, path)];
  });
}

const markdown = `# Scope agent protocol

<!-- Generated by npm run docs:agent. Do not edit by hand. -->

Scope ${pkg.version} exposes agent protocol ${capabilities.protocolVersion} and event format ${capabilities.eventFormatVersion}.
Agents should execute \`scope --json capabilities\` at runtime because workspace-defined statuses can extend this baseline.

This build writes event format ${capabilities.eventFormat.writerVersion}, reads formats ${capabilities.eventFormat.readerVersions.join(', ')}, and requires readers that support format ${capabilities.eventFormat.minimumReaderVersion} for newly written events. All agents sharing a workspace must use a compatible Scope build.

## Machine contract

- Every \`--json\` response is an envelope with \`ok\`, \`protocolVersion\`, and either \`data\` or \`error\`.
- Mutations accept global \`--request-id\` for durable idempotency and \`--if-revision\` for optimistic concurrency.
- Request ids are carried by authoritative events, preventing duplicate mutation even if receipt persistence is interrupted.
- Successful envelopes include the resulting event-set \`meta.revision\` when a workspace is open.
- \`scope watch\` emits one JSON envelope per line and resumes with \`--since <event-id>\`.
- \`scope doctor --json\` audits event/cache parity; \`--repair\` only rebuilds the disposable cache.

## Features

${Object.entries(capabilities.features).map(([name, enabled]) => `- \`${name}\`: ${enabled}`).join('\n')}

## Event kinds

${capabilities.eventKinds.map((kind) => `- \`${kind}\``).join('\n')}

## Commands

${commands(buildProgram()).join('\n')}
`;

if (process.argv.includes('--check')) {
  const current = readFileSync(outputPath, 'utf8');
  if (current !== markdown) {
    process.stderr.write('docs/agent-protocol.md is stale; run npm run docs:agent\n');
    process.exitCode = 1;
  }
} else {
  writeFileSync(outputPath, markdown);
  process.stdout.write(`wrote ${outputPath}\n`);
}
